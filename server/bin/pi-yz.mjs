#!/usr/bin/env node
// pi-yz —— 起 pi-yz 服务端。
//
// ## 为什么要有这条命令
//
// 不然每次都得 `cd <项目路径>/server && npm start` —— 要记住路径，换个目录、
// 换台机器路径就变了。注册成命令之后，任何目录下敲 `pi-yz` 都行。
//
// ## 参数原样透传给服务端入口
//
//   pi-yz                     默认：监听 127.0.0.1，只有本机能连
//   pi-yz --host 0.0.0.0      监听局域网（手机才连得进来）
//   pi-yz --port 8080         换端口
//   pi-yz --tunnel            顺带开一条 SSH 反向隧道（异地也能连）
//   pi-yz --no-pair           不开配对窗口（只有手动指定 token 才配得上）
//   pi-yz --help              完整用法
//
// 这个文件刻意做得极薄：**没有任何逻辑**，只是把控制权交给 index.mjs。
// 逻辑写在这里的话，`npm start` 与 `pi-yz` 两条入口迟早会走偏（之前那个插件
// 版本就是因为有独立的进程管理逻辑，才需要额外维护一份 ctl.mjs）。
import '../index.mjs';
